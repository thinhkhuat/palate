// Cline CLI hook contract (cline/cline SDK, verified against live sources
// 2026-09-16):
//   - sdk/packages/shared/src/hooks/events.ts — every payload (passthrough
//     schema) carries taskId, workspaceRoots []string, agent_id, plus one
//     per-event key: userPromptSubmit{prompt,attachments},
//     postToolUse{toolName,parameters,result,success,executionTimeMs},
//     taskStart/taskResume/taskCancel/taskComplete{taskMetadata}.
//   - sdk/packages/core/src/hooks/hook-file-config.ts — file hooks live in
//     ~/.cline/hooks (plus workspace search paths) and are discovered by
//     basename-minus-extension, matched case-insensitively against the event
//     names, over a fixed extension allowlist ("", .sh, .bash, .zsh, .js,
//     .mjs, .cjs, .ts, .mts, .cts, .py, .ps1). Every matching file fires and
//     the returned contextModification strings are merged — so palate
//     installs collision-free <Event>.mjs shims next to foreign hook files
//     (skill-concierge's ADR-0051 shims use the bare names and .cjs slots).
//   - sdk/packages/core/src/hooks/subprocess.ts — hook stdout is JSON-parsed
//     for {cancel?, contextModification?}; contextModification is the
//     injection channel (50k char cap). Payload arrives on stdin. Node runs
//     extension files (a non-executable .cjs shim fires in production).
//
// Event → palate mapping (palate's hook subcommands are unchanged):
//   TaskStart/TaskResume → hook session-start (source startup/resume)
//   UserPromptSubmit     → hook user-prompt
//   PostToolUse          → hook post-tool-use (Edit/Write-file tools only)
//   TaskComplete/TaskCancel → hook stop (re-baseline + detached distill;
//     Cline has no Stop event and no PreCompact file-hook dispatch — the
//     pre-compact gateway is in-process, so palate's pre-compact handler is
//     not wired here).

// clineShimMarker identifies palate-generated shims for count/uninstall;
// foreign hooks never carry it.
const clineShimMarker = "palate-cline-shim-v1"

// clineShims pairs each Cline file-hook event with the palate subcommand its
// shim invokes.
var clineShims = []struct {
	Event       string
	PalateEvent string
}{
	{"TaskStart", "session-start"},
	{"TaskResume", "session-start"},
	{"UserPromptSubmit", "user-prompt"},
	{"PostToolUse", "post-tool-use"},
	{"TaskComplete", "stop"},
	{"TaskCancel", "stop"},
}

// ClineHooksDir returns the global Cline hook directory (~/.cline/hooks).
func ClineHooksDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".cline", "hooks"), nil
}

func clineShimPath(dir, event string) string {
	return filepath.Join(dir, event+".mjs")
}

// GenerateClineShim renders the shim source for one event. binaryPath is
// stamped verbatim — the installer's own resolved path, which hookBinaryPath
// already degraded from temporary go-build paths to a stable install.
func GenerateClineShim(event, palateEvent, binaryPath string) string {
	body := strings.ReplaceAll(clineShimTemplate, "PALATE_BIN_PLACEHOLDER", binaryPath)
	body = strings.ReplaceAll(body, "PALATE_EVENT_PLACEHOLDER", palateEvent)
	body = strings.ReplaceAll(body, "EVENT_PLACEHOLDER", event)
	return body
}

// clineShimTemplate is the ESM shim body shared by all six events. It reads
// Cline's stdin payload, translates it to the Claude-Code-shaped payload the
// `palate hook <event>` subcommands already parse, and maps palate's
// hookSpecificOutput/systemMessage back to Cline's contextModification.
// Fail-open by contract: any error emits {cancel:false} and exits 0.
const clineShimTemplate = `/**
 * palate → Cline hook shim — EVENT_PLACEHOLDER (palate hook PALATE_EVENT_PLACEHOLDER)
 * GENERATED by palate hook install --harness cline — safe to regenerate; edits are lost.
 * Marker: palate-cline-shim-v1. Cline fires this alongside the operator's own
 * hook files and merges the returned contextModification strings
 * (hook-file-config.ts + subprocess.ts). Payload: JSON on stdin; output: one
 * JSON line { cancel?: bool, contextModification?: string }. Fail-open.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const PALATE_BIN = 'PALATE_BIN_PLACEHOLDER';
const EVENT = 'EVENT_PLACEHOLDER';
const PALATE_EVENT = 'PALATE_EVENT_PLACEHOLDER';

const out = (o) => { process.stdout.write(JSON.stringify(o) + '\n'); process.exit(0); };
const failOpen = () => out({ cancel: false });

// transcriptFor resolves the session transcript for taskId: the deterministic
// <dir>/<dir>.messages.json first, then a metadata scan for session_id (the
// <dir>.json record carries session_id and messages_path). '' when unknown —
// palate's hook handlers skip the distiller without a transcript path.
function transcriptFor(taskId) {
  if (!taskId) return '';
  const root = path.join(os.homedir(), '.cline', 'data', 'sessions');
  const direct = path.join(root, taskId, taskId + '.messages.json');
  try { if (fs.existsSync(direct)) return direct; } catch { /* fall through */ }
  try {
    for (const d of fs.readdirSync(root)) {
      try {
        const meta = JSON.parse(fs.readFileSync(path.join(root, d, d + '.json'), 'utf8'));
        if (meta.session_id === taskId && meta.messages_path) return String(meta.messages_path);
      } catch { /* skip unreadable session */ }
    }
  } catch { /* no sessions dir */ }
  return '';
}

function runPalate(stdinPayload) {
  let r;
  try {
    r = spawnSync(PALATE_BIN, ['hook', PALATE_EVENT], {
      input: stdinPayload, timeout: 45000, encoding: 'utf8',
    });
  } catch { return null; }
  const lines = String(r.stdout || '').split('\n').map(l => l.trim()).filter(Boolean);
  for (let i = lines.length - 1; i >= 0; i--) {
    try { return JSON.parse(lines[i]); } catch { /* try the next line */ }
  }
  return null;
}

function main() {
  let p;
  try { p = JSON.parse(fs.readFileSync(0, 'utf8')); } catch { return failOpen(); }
  const taskId = String(p.taskId || '');
  const cwd = (Array.isArray(p.workspaceRoots) && p.workspaceRoots[0]) || process.cwd();
  let payload = null;

  switch (EVENT) {
    case 'TaskStart':
    case 'TaskResume': {
      payload = {
        session_id: taskId,
        transcript_path: transcriptFor(taskId),
        cwd,
        source: EVENT === 'TaskStart' ? 'startup' : 'resume',
      };
      break;
    }
    case 'UserPromptSubmit': {
      const prompt = String((p.userPromptSubmit || {}).prompt || '');
      if (!prompt.trim()) return failOpen();
      payload = { prompt };
      break;
    }
    case 'PostToolUse': {
      const ptu = p.postToolUse || {};
      const params = ptu.parameters || {};
      // Cline stringifies parameter values (mapParams); file_path may arrive
      // as a plain path or a JSON-quoted string — tolerate both.
      const raw = params.file_path || params.path || '';
      let fp = String(raw);
      if (fp.length > 1 && fp.startsWith('"')) {
        try { fp = String(JSON.parse(fp)); } catch { /* keep raw */ }
      }
      if (!fp) return failOpen();
      payload = {
        tool_name: String(ptu.toolName || ''),
        tool_input: { file_path: fp },
        session_id: taskId,
      };
      break;
    }
    case 'TaskComplete':
    case 'TaskCancel': {
      payload = { session_id: taskId, transcript_path: transcriptFor(taskId), cwd };
      break;
    }
    default:
      return failOpen();
  }

  const resp = runPalate(JSON.stringify(payload));
  const parts = [];
  if (resp && typeof resp === 'object') {
    if (resp.systemMessage) parts.push(String(resp.systemMessage));
    const hs = resp.hookSpecificOutput;
    if (hs && hs.additionalContext) parts.push(String(hs.additionalContext));
  }
  out(parts.length ? { cancel: false, contextModification: parts.join('\n\n') } : { cancel: false });
}

try { main(); } catch { out({ cancel: false }); }
`

// writeClineShimsAt writes the palate shims into dir, preserving every
// foreign file. Idempotent: an existing palate shim is backed up once
// (backupBeforeWrite) and replaced. A foreign file occupying a target path
// (no palate marker) makes the install FAIL with a naming conflict — Cline
// fires every file matching an event name, so overwriting it would silently
// kill a foreign hook. The operator resolves the conflict by hand.
// Returns the number of shims written.
func writeClineShimsAt(dir, binaryPath string) (int, error) {
	if err := os.MkdirAll(dir, 0755); err != nil {
		return 0, err
	}
	// Conflict pre-check across all targets before writing anything, so a
	// conflicting install leaves no half-written state behind.
	for _, s := range clineShims {
		p := clineShimPath(dir, s.Event)
		if info, err := os.Stat(p); err == nil && !info.IsDir() && !isPalateClineShim(p) {
			return 0, fmt.Errorf("hook conflict: %s is not a palate shim (no %s marker); remove or rename it yourself — palate will not overwrite a foreign hook", p, clineShimMarker)
		}
	}
	written := 0
	for _, s := range clineShims {
		p := clineShimPath(dir, s.Event)
		if err := backupBeforeWrite(p); err != nil {
			return written, err
		}
		if err := os.WriteFile(p, []byte(GenerateClineShim(s.Event, s.PalateEvent, binaryPath)), 0755); err != nil {
			return written, err
		}
		written++
	}
	return written, nil
}

// WriteClineHooksGlobal installs the palate shims into ~/.cline/hooks. Cline
// discovers hook files at dispatch time from the global directory (plus
// workspace search paths), so the global directory is the vehicle — there is
// no separate workspace config to merge into, unlike ZCode.
func WriteClineHooksGlobal(binaryPath string) error {
	dir, err := ClineHooksDir()
	if err != nil {
		return err
	}
	_, err = writeClineShimsAt(dir, binaryPath)
	return err
}

// isPalateClineShim reports whether the file at path is a palate-generated
// shim (event name and marker both match) — the uninstall safety check that
// guarantees foreign hooks are never removed.
func isPalateClineShim(path string) bool {
	base := filepath.Base(path)
	if !strings.HasSuffix(base, ".mjs") {
		return false
	}
	event := strings.TrimSuffix(base, ".mjs")
	known := false
	for _, s := range clineShims {
		if s.Event == event {
			known = true
			break
		}
	}
	if !known {
		return false
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	return strings.Contains(string(data), clineShimMarker)
}

// CountClineHooks counts palate shims in the Cline hook directory at dir
// (0 when the directory does not exist).
func CountClineHooks(dir string) int {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return 0
	}
	n := 0
	for _, e := range entries {
		if !e.IsDir() && isPalateClineShim(filepath.Join(dir, e.Name())) {
			n++
		}
	}
	return n
}

// RemoveClineHooks removes every palate shim from the hook directory at dir,
// preserving foreign files. Returns the number removed.
func RemoveClineHooks(dir string) (int, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return 0, nil
		}
		return 0, err
	}
	removed := 0
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		p := filepath.Join(dir, e.Name())
		if !isPalateClineShim(p) {
			continue
		}
		if err := os.Remove(p); err != nil {
			return removed, err
		}
		removed++
	}
	return removed, nil
}

// RemoveClineHooksGlobal removes the palate shims from ~/.cline/hooks.
func RemoveClineHooksGlobal() (int, error) {
	dir, err := ClineHooksDir()
	if err != nil {
		return 0, err
	}
	return RemoveClineHooks(dir)
}

// ClineWiringDetail returns the doctor detail string for a wired install.
func ClineWiringDetail(dir string) string {
	return fmt.Sprintf("%d hook shims", CountClineHooks(dir))
}


